"""The sync schedule on Linux: a systemd service + timer per brain.

The macOS counterpart is the LaunchAgent in project.py. Same contract: one
job per brain, named after the brain's namespace, re-running
`brain sync <project> --full`; the unit records which project it belongs to
so a second brain can never take over the first one's schedule.

Two install locations, chosen by who runs `brain schedule`:
  - a normal user: ~/.config/systemd/user, managed with `systemctl --user`
    (the user needs lingering — `loginctl enable-linger` — for the timer to
    run while they are logged out);
  - root: /etc/systemd/system, with `User=` set to the owner of the project
    folder, so the sync never runs as root. This is the server case: the brain
    belongs to a service account that has no session of its own.
"""
from __future__ import annotations

import os
import pwd
import shutil
import subprocess
from pathlib import Path

from brainiphy_cli import ui
from brainiphy_cli.storage import atomic_write

PREFIX = "brainiphy-sync-"
_DEFAULT_PATH = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
_PROJECT_TAG = "# brainiphy-project: "
_NAMESPACE_TAG = "# brainiphy-namespace: "


def is_system() -> bool:
    return os.geteuid() == 0


def unit_dir() -> Path:
    if is_system():
        return Path("/etc/systemd/system")
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "systemd" / "user"


def _systemctl() -> list[str]:
    return ["systemctl"] if is_system() else ["systemctl", "--user"]


def _quote(value: str) -> str:
    """One argument of an Exec line. systemd expands % and $ and splits on
    spaces, so a project path like "/srv/Acme 100%" has to be escaped."""
    escaped = (value.replace("\\", "\\\\").replace('"', '\\"')
               .replace("%", "%%").replace("$", "$$"))
    return f'"{escaped}"'


def _tag(path: Path, tag: str) -> str | None:
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith(tag):
                return line[len(tag):].strip()
    except (OSError, UnicodeDecodeError):
        pass
    return None


def belongs_to(service: Path, project: Path) -> bool:
    recorded = _tag(service, _PROJECT_TAG)
    return bool(recorded) and Path(recorded).resolve() == project.resolve()


def has_namespace(service: Path, namespace: str) -> bool:
    return _tag(service, _NAMESPACE_TAG) == namespace


def find(project: Path) -> Path | None:
    """The timer that keeps this project in sync, or None."""
    folder = unit_dir()
    for service in sorted(folder.glob(f"{PREFIX}*.service")):
        timer = service.with_suffix(".timer")
        if belongs_to(service, project) and timer.exists():
            return timer
    return None


def _path_env() -> str:
    dirs: list[str] = []
    for exe in ("brain", "graphify", "claude"):
        found = shutil.which(exe)
        if found and str(Path(found).parent) not in dirs:
            dirs.append(str(Path(found).parent))
    return ":".join([*dirs, _DEFAULT_PATH])


def render(project: Path, *, name: str, namespace: str, brain_exe: str,
           interval_seconds: int, log_dir: Path, run_as: str | None) -> tuple[str, str]:
    """The (service, timer) unit texts. Pure, so the tests can read them."""
    registry = project / "connectors" / "registry.yaml"
    service = [
        _PROJECT_TAG + str(project),
        _NAMESPACE_TAG + namespace,
        "# Generated by `brain schedule` — regenerate instead of editing by hand.",
        "[Unit]",
        f"Description=brainiphy sync ({name})",
        # A brain on a volume that is not mounted yet (an encrypted disk that
        # is opened by hand after a reboot) is skipped, not reported as failed.
        f"ConditionPathExists={str(registry).replace('%', '%%')}",
        "",
        "[Service]",
        "Type=oneshot",
    ]
    if run_as:
        service.append(f"User={run_as}")
    service += [
        f"Environment={_quote('PATH=' + _path_env())}",
        f"ExecStart={_quote(brain_exe)} sync {_quote(str(project))} --full",
        f"StandardOutput=append:{log_dir / 'sync.out.log'}",
        f"StandardError=append:{log_dir / 'sync.err.log'}",
        "",
    ]
    timer = [
        _PROJECT_TAG + str(project),
        "[Unit]",
        f"Description=brainiphy sync timer ({name})",
        "",
        "[Timer]",
        "OnBootSec=2min",
        # Counted from the end of the previous run, so a slow sync never
        # overlaps the next one.
        f"OnUnitInactiveSec={interval_seconds}s",
        "",
        "[Install]",
        "WantedBy=timers.target",
        "",
    ]
    return "\n".join(service), "\n".join(timer)


def schedule(project: Path, *, name: str, namespace: str, brain_exe: str,
             interval_minutes: float, explicit_name: bool, load: bool) -> bool:
    folder = unit_dir()
    service_path = folder / f"{PREFIX}{name}.service"

    # Keep an existing job's name if it belongs to this exact project.
    existing = next((s for s in sorted(folder.glob(f"{PREFIX}*.service"))
                     if belongs_to(s, project)), None)
    if existing is None:
        existing = next((s for s in sorted(folder.glob(f"{PREFIX}*.service"))
                         if has_namespace(s, namespace)), None)
    if existing and not explicit_name:
        service_path = existing
    if (service_path.exists() and not belongs_to(service_path, project)
            and not has_namespace(service_path, namespace)):
        ui.error("schedule name is already used by another project:", service_path)
        return False
    timer_path = service_path.with_suffix(".timer")

    run_as = None
    if is_system():
        owner = pwd.getpwuid(project.stat().st_uid).pw_name
        if owner == "root":
            ui.error("the project folder belongs to root — give it to the account the "
                     "sync should run as, so it does not run as root")
            return False
        run_as = owner

    log_dir = project / "connectors" / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    if run_as:
        shutil.chown(log_dir, user=run_as)
    unit_name = service_path.stem[len(PREFIX):]
    service, timer = render(
        project, name=unit_name, namespace=namespace, brain_exe=brain_exe,
        interval_seconds=int(interval_minutes * 60), log_dir=log_dir, run_as=run_as)
    folder.mkdir(parents=True, exist_ok=True)
    atomic_write(service_path, service)
    atomic_write(timer_path, timer)
    ui.ok("wrote", service_path)
    ui.ok("wrote", timer_path)

    ctl = _systemctl()
    enable = [*ctl, "enable", "--now", timer_path.name]
    if not load:
        ui.hint("not active yet — to activate it:",
                " ".join([*ctl, "daemon-reload"]) + " && " + " ".join(enable))
        return True
    for cmd in ([*ctl, "daemon-reload"], enable, [*ctl, "restart", timer_path.name]):
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            ui.raw(result.stderr, stderr=True)
            ui.error(" ".join(cmd[:len(ctl) + 1]) + " failed")
            return False
    ui.ok(f"timer enabled with systemd, runs every {interval_minutes:g} min")
    if not is_system():
        ui.hint("to keep it running while you are logged out:",
                f"loginctl enable-linger {pwd.getpwuid(os.getuid()).pw_name}")
    return True
